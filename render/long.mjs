// Long videos (16:9, YouTube): one scene per problem (user's rule, 2026-10-26). Each scene is a
// lesson of its own (voice.json, timing.json, scene.js, audio/, its own index.html and its own MP4);
// the lesson's index.html is the stitched preview that plays the scenes one after another.
//
//   lessons/<date>/long/<lang>/<lesson>/
//     scenes.json          { "title", "final"?, "scenes": [{ "id": "scene1", "title": "Bài 1" }, ...] }
//     index.html           stitched preview (shared/web/js/playlist.js), generated
//     story.md critique.md and helpers shared by the scenes (problems.js, ...)
//     scene1/ scene2/ ...  voice.json, scene.js, timing.json, audio/, index.html (generated)
//
//   node render/long.mjs <lesson>            (npm run scenes -- <lesson>) creates the folders of the
//        scenes listed in scenes.json that are missing (starter voice.json + scene.js) and rewrites
//        every index.html; run it after adding, removing or renaming a scene
//   node render/long.mjs <lesson> --seams    renders the last frame of each scene and the first frame
//        of the next one into <lesson>/out/seams/{end,start}/ and diffs them (mean 0 = seamless cut)
//
// npm run new -- <lesson> --scenes 3 creates a long lesson with scene1..scene3 (it runs
// node render/long.mjs <lesson> --create 3 on the new folder).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { lessonDir, lessonInfo, listScenes, SCENES } from './paths.mjs';

const VOICES = { vi: 'vi-VN-HoaiMyNeural', en: 'en-US-AvaNeural' };
const WORD = { vi: 'Bài', en: 'Problem' };
const up = (dir) => '../'.repeat(dir.split(path.sep).length);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

// one scene on its own: the shared player, reading the scene's timing.json next to the page
export function sceneHtml({ root, title, lang = 'vi' }) {
  return `<!doctype html>
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <title>${esc(title)}</title>
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <link rel="icon" href="data:,">
  <link rel="stylesheet" href="${root}shared/web/css/board.css">
</head>
<!-- generated by render/long.mjs; the scene itself is scene.js + timing.json in this folder -->
<body data-timing="./timing.json">
  <div id="stage"></div>

  <div id="controls">
    <button id="play">▶</button>
    <input id="scrub" type="range" min="0" max="1000" value="0">
    <span id="time">0.00 s</span>
    <span id="beat"></span>
  </div>

  <script type="module" src="${root}shared/web/js/player.js"></script>
</body>
</html>
`;
}

// the stitched preview: plays every scene page of scenes.json in order on one timeline
export function playlistHtml({ root, scenes, title, lang = 'vi' }) {
  return `<!doctype html>
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <title>${esc(title)}</title>
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <link rel="icon" href="data:,">
  <link rel="stylesheet" href="${root}shared/web/css/playlist.css">
</head>
<!-- generated by render/long.mjs; scene order and titles come from scenes.json -->
<body data-scenes="${scenes}">
  <div id="screen"></div>

  <div id="controls">
    <button id="play">▶</button>
    <input id="scrub" type="range" min="0" max="1000" value="0">
    <span id="time">0:00</span>
    <span id="now"></span>
  </div>
  <ol id="chapters"></ol>

  <script type="module" src="${root}shared/web/js/playlist.js"></script>
</body>
</html>
`;
}

function starterVoice(lang, n, first) {
  return {
    lang, profile: 'landscape', voice: VOICES[lang], rate: '+0%', fps: 30, gap: 0.35,
    beats: [first
      ? { id: 'beat1', lead: 0.8, tail: 1.0, lines: [{ id: 'L1', text: `${WORD[lang]} ${n}.` }],
        windows: { title: ['L1^', 0.8] } }
      // a later scene opens by wiping the previous scene's last board (see scene.js)
      : { id: 'beat1', prev: 'from_prev', lead: 1.4, tail: 1.0, lines: [{ id: 'L1', text: `${WORD[lang]} ${n}.` }],
        windows: { wipe: ['beat^', 1.2, 'raw'], title: ['L1^', 0.8] } }],
  };
}

function starterScene(lang, n, prev, root) {
  const shared = `${root}shared/web/js`;
  return `// ${WORD[lang]} ${n}. Beats as in every lesson: beatN(ctx, p), keys missing from p count as 1.
import { g } from '${shared}/fx.js';
${prev ? `// the previous scene's last board, wiped away by this scene's first beat ("prev": "from_prev")
import { scenes as previous } from '../${prev}/scene.js';
` : ''}
export const scenes = {
${prev ? `  from_prev: previous.beat1, // set to the previous scene's LAST beat
` : ''}  beat1(ctx, p) {
    ctx.chalk(60).text('${WORD[lang]} ${n}', 960, 560, { size: 120, align: 'center', t: g(p, 'title') });
  },
};
`;
}

// create the folders of missing scenes, then (re)write every index.html of the lesson
export function syncScenes(lesson) {
  const dir = lessonDir(lesson);
  const { lang } = lessonInfo(lesson);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, SCENES), 'utf8'));
  const scenes = listScenes(lesson);
  scenes.forEach((s, i) => {
    fs.mkdirSync(s.dir, { recursive: true });
    const voice = path.join(s.dir, 'voice.json');
    const code = path.join(s.dir, 'scene.js');
    if (!fs.existsSync(voice)) fs.writeFileSync(voice, `${JSON.stringify(starterVoice(lang, i + 1, i === 0), null, 2)}\n`);
    if (!fs.existsSync(code)) fs.writeFileSync(code, starterScene(lang, i + 1, i ? scenes[i - 1].id : null, up(s.dir)));
    fs.writeFileSync(path.join(s.dir, 'index.html'),
      sceneHtml({ root: up(s.dir), title: `${manifest.title} · ${s.title}`, lang }));
  });
  fs.writeFileSync(path.join(dir, 'index.html'),
    playlistHtml({ root: up(dir), scenes: `./${SCENES}`, title: manifest.title, lang }));
  return scenes;
}

// new long lesson with scene1..sceneN (the folder itself is made by paths.mjs newLessonDir)
export function createScenes(lesson, count) {
  if (!(count >= 1)) throw new Error(`--scenes must be a number >= 1, got "${count}"`);
  const dir = lessonDir(lesson);
  const { lang } = lessonInfo(lesson);
  const scenes = Array.from({ length: count }, (_, i) => ({ id: `scene${i + 1}`, title: `${WORD[lang]} ${i + 1}` }));
  fs.writeFileSync(path.join(dir, SCENES), `${JSON.stringify({ title: lesson, scenes }, null, 2)}\n`);
  return syncScenes(lesson);
}

// a script given a long lesson (not one scene) runs once per scene: node <script> <lesson>/<scene> ...
// -> true when it did (the caller stops there); exit code 1 if any scene failed
export function perScene(lesson, script, rest = []) {
  if (!lesson || lesson.includes('/')) return false;
  const scenes = listScenes(lesson);
  if (!scenes.length) return false;
  for (const s of scenes) {
    console.log(`--- ${s.ref}`);
    try {
      execFileSync(process.execPath, [script, s.ref, ...rest], { stdio: 'inherit' });
    } catch {
      process.exitCode = 1;
    }
  }
  return true;
}

async function seams(lesson) {
  const { openPlayer } = await import('./browser.mjs');
  const scenes = listScenes(lesson);
  const out = path.join(lessonDir(lesson), 'out', 'seams');
  for (const k of ['end', 'start']) fs.mkdirSync(path.join(out, k), { recursive: true });
  for (let i = 1; i < scenes.length; i++) {
    for (const [k, s, at] of [['end', scenes[i - 1], (t) => Math.round(t.duration * t.fps - 1) / t.fps], ['start', scenes[i], () => 0]]) {
      const player = await openPlayer({ lesson: s.ref });
      try {
        fs.writeFileSync(path.join(out, k, `${scenes[i].id}.png`), await player.shot(at(player.timing)));
      } finally {
        await player.close();
      }
    }
  }
  console.log(`seams: last frame of the previous scene vs first frame of each scene (${out})`);
  execFileSync(process.execPath, ['render/inspect.mjs', 'diff', path.join(out, 'end'), path.join(out, 'start')], { stdio: 'inherit' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [lesson, flag, count] = process.argv.slice(2);
  if (!lesson) throw new Error('usage: node render/long.mjs <lesson> [--seams]');
  if (flag === '--seams') await seams(lesson);
  else {
    for (const s of flag === '--create' ? createScenes(lesson, Number(count)) : syncScenes(lesson)) console.log(`${s.dir}/index.html  ${s.title}`);
    console.log(`${lessonDir(lesson)}/index.html  (all scenes)`);
  }
}
